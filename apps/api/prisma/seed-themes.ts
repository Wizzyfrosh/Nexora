async function main() {
  console.log('Start seeding themes...');
  for (const theme of themes) {
    const upserted = await prisma.theme.upsert({
      where: { themeId: theme.themeId },
      update: theme,
      create: theme,
    });
    console.log(`Upserted theme: ${upserted.name} (${upserted.themeId})`);
  }
  console.log('Seeding finished.');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
